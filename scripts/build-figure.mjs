import fs from 'node:fs';
import * as k from '../vendor/anatomy/iso-kit.mjs';
const plan={x:-65,y:-45,w:130,d:90,r:5};
const P=k.fitProjection(k.boxCorners({x:-75,y:-50,w:150,d:130,r:0},-10,125),650,510,{pad:48,azimuth:38,elevation:28});
const s=(p,z,h,tone='mid')=>k.solidSvg(k.slabOf(p,z,h,P,5,.7),{tone});
const box=(x,y,w,d,z,h,t='mid')=>s({x,y,w,d,r:1.3},z,h,t);
const dot=(x,y,z)=>k.dotsSvg([k.iso([x,y,z],P)],{size:.7,tone:'hi'});
let out=`<path class="iso-halo" d="${k.haloOf(plan,-10,8,P)}"/>`;
for(const [x,y] of k.corners(plan,12))out+=box(x-4,y-4,8,8,-10,7,'lo');
out+=s(plan,-3,8,'lo');
for(const [x,y] of k.corners(plan,7))out+=dot(x,y,5);
out+=box(-63,-44,126,4,5,105,'lo');
for(const x of [-64,59])out+=box(x,-40,5,82,5,105,'mid');
for(const x of [-59,53])for(const y of [-38,35])out+=box(x,y,6,6,5,105,'hi');
for(let i=2;i>=0;i--){const z=12+i*29;out+=box(-53,-36,4,76,z,3,'lo')+box(49,-36,4,76,z,3,'lo');
let drawer=box(-48,-34,96,68,z+3,3,'hi')+box(-49,30,98,5,z+3,23,'hi');
for(const x of [-32,28])drawer+=box(x,35,4,5,z+11,4,'mid');
drawer+=box(-32,39,64,4,z+11,4,'mid');
for(const x of [-41,41])for(const zz of [z+7,z+22])drawer+=k.dotsSvg([k.iso([x,35,zz],P)],{size:.6});
drawer+=box(-19,35,38,.5,z+19,4,'lo');
for(const x of [35,39])drawer+=box(x,35,2,1,z+13,2,'lo');
const end=k.iso([0,22,0],P),start=k.iso([0,0,0],P);
out+=`<g class="drawer" data-drawer="${i}" style="--dx:${end[0]-start[0]}px;--dy:${end[1]-start[1]}px">${drawer}</g>`;
}
out+=s({x:-66,y:-46,w:132,d:93,r:4},110,7,'hi');
out+=k.lineSvg(k.planOutline({x:-61,y:-41,w:122,d:83,r:3},117,P),{tone:'lo'});
for(const [x,y] of k.corners(plan,8))out+=dot(x,y,117);
for(let i=0;i<8;i++)out+=box(-42+i*10,-24,4,36,117,.4,'lo');
const svg=k.figureSvg({width:650,height:510,label:'Illustration pédagogique : un serveur personnel à trois tiroirs, pour les fichiers, les photos et les échanges entre proches.',body:out});
fs.writeFileSync(new URL('../dist/assets/station.svg',import.meta.url),k.figureSvg({width:650,height:510,label:'Une station personnelle astroportd, illustration pédagogique.',body:out,standalone:'light'}));
fs.writeFileSync(new URL('../dist/assets/figure.html',import.meta.url),svg);
console.log('Figure Anatomy générée : 3 tiroirs, SVG autonome et fragment HTML.');
